def svg(name: str, color: str = "#475569", stroke: float = 2.0) -> str:
    body = _PATHS.get(name, _PATHS["info"])
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="{color}" '
        f'stroke-width="{stroke}" stroke-linecap="round" stroke-linejoin="round">{body}</svg>'
    )


def _render(svg_text: str, size: int) -> QPixmap:
    renderer = QSvgRenderer(QByteArray(svg_text.encode("utf-8")))
    pm = QPixmap(size * 2, size * 2)  # 2x for crisp HiDPI rendering
    pm.fill(Qt.transparent)
    p = QPainter(pm)
    p.setRenderHint(QPainter.Antialiasing)
    renderer.render(p, QRectF(0, 0, size * 2, size * 2))
    p.end()
    pm.setDevicePixelRatio(2.0)
    return pm


@lru_cache(maxsize=256)
def icon(name: str, color: str = "#475569", size: int = 18) -> QIcon:
    return QIcon(_render(svg(name, color), size))


@lru_cache(maxsize=64)
def pixmap(name: str, color: str = "#475569", size: int = 18) -> QPixmap:
    return _render(svg(name, color), size)


def nav_icon(name: str) -> QIcon:
    """Icon that brightens when its navigation button is active/hovered."""
    ic = QIcon()
    ic.addPixmap(_render(svg(name, "#9FB0C8"), 18), QIcon.Normal, QIcon.Off)
    ic.addPixmap(_render(svg(name, "#FFFFFF"), 18), QIcon.Normal, QIcon.On)
    ic.addPixmap(_render(svg(name, "#FFFFFF"), 18), QIcon.Active, QIcon.Off)
    return ic


